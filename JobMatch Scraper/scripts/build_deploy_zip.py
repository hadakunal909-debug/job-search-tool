#!/usr/bin/env python3
"""
build_deploy_zip.py — pack the app for a manual cPanel upload.

WHY THIS EXISTS: deploys are supposed to happen through cPanel Git Version Control
running .cpanel.yml, but its DEPLOYPATH still points at /home/bnrqpozr/Stemjobs — the
account suspended around 2026-07-21 — so a git deploy copies files into a home nobody
serves and silently changes nothing. Until that path is fixed, uploading a zip is the
way in. This packs EXACTLY the same file list .cpanel.yml deploys, so the two stay in
step and switching back later changes nothing.

    python scripts/build_deploy_zip.py            -> ../stemjobs1_deploy.zip
    python scripts/build_deploy_zip.py out.zip

The archive is FLAT: its entries sit at the root, so extracting it inside the app
directory on the server lands every file exactly where Passenger expects it.

NOT included, deliberately:
  .env / secrets            never leave this machine
  jdmeta.json               ~21 MB, regenerated by the scraper on its own host
  scripts/                  verification tools, not runtime
  __pycache__, *.pyc        stale bytecode breaks more deploys than it fixes
"""
import os
import sys
import zipfile

# Mirrors the /bin/cp list in .cpanel.yml. Keep the two in sync.
FILES = [
    "web.py", "core.py", "db.py", "auth.py", "passenger_wsgi.py",
    "requirements-cpanel.txt", "idf.json", "careers_us.md", "sponsors.txt",
]
# Present-if-built data files. Each feature stays dormant without its file, which is the
# contract core.load_sponsor_counts / load_everify already have — so a missing one is fine.
OPTIONAL_FILES = ["sponsor_counts.json", "everify.txt"]
DIRS = ["scraper", "resume_brain", "templates", "static"]
SKIP_DIRS = {"__pycache__", ".pytest_cache"}
SKIP_EXT = {".pyc", ".pyo"}


def main():
    app = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    os.chdir(app)
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join("..", "stemjobs1_deploy.zip")

    missing = [f for f in FILES if not os.path.isfile(f)]
    if missing:
        sys.exit("  Refusing to build an incomplete bundle — missing: %s" % ", ".join(missing))

    added, skipped = [], []
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for f in FILES:
            z.write(f, f)
            added.append(f)
        for f in OPTIONAL_FILES:
            if os.path.isfile(f):
                z.write(f, f)
                added.append(f)
            else:
                skipped.append(f)
        for d in DIRS:
            if not os.path.isdir(d):
                skipped.append(d + "/")
                continue
            for root, dirnames, filenames in os.walk(d):
                dirnames[:] = [x for x in dirnames if x not in SKIP_DIRS]
                for name in sorted(filenames):
                    if os.path.splitext(name)[1] in SKIP_EXT:
                        continue
                    p = os.path.join(root, name)
                    z.write(p, p.replace(os.sep, "/"))
                    added.append(p)

    size = os.path.getsize(out)
    print("Wrote %s  (%d files, %.1f MB)" % (os.path.abspath(out), len(added), size / 1e6))
    if skipped:
        print("Not present, so not included: %s" % ", ".join(skipped))
    print("\nUpload it in cPanel -> File Manager -> the app's directory -> Upload,")
    print("then Extract, then touch tmp/restart.txt so Passenger reloads.")


if __name__ == "__main__":
    main()
